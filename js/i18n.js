let lang = 'en';

export function setLang(pref) {
  if (pref === 'de' || pref === 'en') lang = pref;
  else lang = 'de'; // German by default
  document.documentElement.lang = lang;
  return lang;
}

export function getLang() { return lang; }

export function t(key, ...args) {
  const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

export function pick(key) {
  const arr = t(key);
  return Array.isArray(arr) ? arr[Math.floor(Math.random() * arr.length)] : arr;
}

// Fill every [data-i18n] element in the DOM.
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
}
